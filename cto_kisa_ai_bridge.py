"""Route explicit KISA/CVE questions into verified Neo4j 1-hop evidence + Qwen.

Does not disable CTO worker citations for OpenStack questions. KISA results
are labeled as model-generated explanations WITHOUT CTO Citation PASS.
"""
from __future__ import annotations
import re
from cto_kisa_rag import retrieve, ai_prompt, is_kisa_question


def match_user_question(q):
    q=str(q or '').strip()
    if len(q)>2500:return False
    # Do not confuse raw log/prompt text containing incidental CVE references.
    return is_kisa_question(q)


def maybe_answer(question, db_query, qwen_runner, *, raw_event=None, timeout=180):
    if not match_user_question(question):return None
    result=retrieve(question,db_query,limit=6)
    if result.get('no_match'):
        return {'answer':'### KISA 공식 공지 검색\n\n요청과 일치하는 KISA 공지를 Neo4j에서 찾지 못했습니다. '
                         '이는 취약점이 존재하지 않는다는 증거가 아닙니다. KISA RSS 수집 상태와 검색어를 확인하세요.',
                'model':'KISA 조회만 수행','elapsed_sec':0,'tools':['kisa_neo4j_retrieve'],
                'citation_status':'unverified','citation_reason':'KISA 일치 공지가 없어 AI 생성하지 않음',
                'citation_called':False,'validated':False}
    prompt=ai_prompt(question,result)
    if isinstance(raw_event,dict) and raw_event:
        # A log can be provided for context, but KISA advisory != proof of an exploit.
        source=str(raw_event.get('source_type') or raw_event.get('event_type') or '')[:120]
        prompt+='\n[사용자가 별도로 선택한 로그의 출처]\n'+source+\
                '\n공지만으로 이 로그가 취약점 악용의 증거라고 말하지 마라.\n'
    resp=qwen_runner(prompt,timeout=min(max(int(timeout),1),180))
    answer=str(resp.get('answer') or '').strip() if isinstance(resp,dict) else ''
    if not answer:raise RuntimeError('KISA 기반 Qwen 답변이 비어 있습니다.')
    references=[]
    for f in result.get('facts',[]):
        url=str(f.get('url') or '')
        if url and url not in references:references.append(url)
    # Trusted links emitted by code, NOT generated by the model. HTML escaping
    # isn't needed in plaintext; Markdown special characters are protected.
    if references:
        answer+='\n\n### 확인된 KISA 공식 원문\n'+'\n'.join('- '+u for u in references[:6])
    answer+='\n\n*출처: KISA 공식 공지 상세·RSS 메타데이터. 이 답변은 Qwen 직접 API 설명이며 기존 CTO Citation PASS가 아닙니다.*'
    return {'answer':answer,'elapsed_sec':resp.get('elapsed_sec') if isinstance(resp,dict) else None,
            'model':resp.get('model') if isinstance(resp,dict) else None,
            'tools':['kisa_neo4j_retrieve','qwen_direct_api'],
            'citation_status':'unverified',
            'citation_reason':'KISA 공식 원문 링크는 Neo4j에서 검증. CTO Citation 검증은 미적용',
            'citation_called':False,'validated':False,'citation_checks':[],
            'progress_steps':[],'harness_metrics':{'kisa_advisories':len(result.get('facts') or []),
            'kisa_verified_urls':len(references)},'execution_mode':'kisa_direct_evidence'}
